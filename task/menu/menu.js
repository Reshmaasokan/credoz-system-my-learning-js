function menuselection(drinks){

    switch (drinks){
        case 1:
            console.log("Espresso")
            break;
        case 2:
            console.log("Latte")
            break;
        case 3:
            console.log("Cappuccino")
            break;
        default:
            console.log("Invalid Selection")
    }

}
menuselection(6)